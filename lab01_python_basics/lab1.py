"""Лабораторна робота №1. Основи мови Python.

Лінійні алгоритми: введення даних, арифметичні операції, робота зі списком.
"""

# Завдання 1. Чотири змінні, значення яких вводить користувач.
# float() приймає і цілі ("5"), і дробові ("2.5") числа.
# Для цілих чисел зберігаємо тип int, щоб результати виглядали природно.
def read_number(prompt):
    """Зчитує число з клавіатури: int, якщо введено ціле, інакше float."""
    text = input(prompt).strip().replace(",", ".")
    value = float(text)
    return int(value) if value.is_integer() and "." not in text else value


a = read_number("Введіть ціле число a: ")
b = read_number("Введіть ціле число b: ")
c = read_number("Введіть дробове число c: ")
d = read_number("Введіть дробове число d: ")
print(f"a = {a}, b = {b}, c = {c}, d = {d}")

# Завдання 2. Арифметичні дії над числами; результати записуємо у список.
# Пари операндів обрано так, щоб задіяти всі чотири змінні.
results = [
    a + b,    # додавання
    c - d,    # віднімання
    a * c,    # множення
    b / d,    # ділення
    a ** b,   # піднесення до степеня
    c // b,   # цілочисельне ділення
    a % b,    # остача від ділення
]
names = ["a + b", "c - d", "a * c", "b / d", "a ** b", "c // b", "a % b"]
for name, value in zip(names, results):
    print(f"{name:>7} = {value}")
print("Список результатів:", results)

# Завдання 3. Кількість елементів і парні елементи списку.
# Парним вважаємо число, яке є цілим і ділиться на 2 без остачі
# (дробові результати, наприклад 3.75, парними не бувають).
print("Кількість елементів у списку:", len(results))
even = [x for x in results if float(x).is_integer() and int(x) % 2 == 0]
print("Парні елементи списку:", even)

# Завдання 4. Міняємо місцями другий (індекс 1) і п'ятий (індекс 4) елементи.
results[1], results[4] = results[4], results[1]
print("Список після обміну 2-го і 5-го елементів:", results)

# Завдання 5. Інформація про виконавця та висновки (кожне речення з нового рядка).
name = input("Введіть ваше прізвище та ім'я: ")
print(f"Лабораторну роботу №1 виконав(ла): {name}.")
print("Висновки:")
print("Я ознайомився(лася) з лінійними алгоритмами та запуском програм на Python.")
print("Функція input() повертає рядок, тому його треба перетворювати на число.")
print("Оператори / і // відрізняються: перший дає дійсну частку, другий - цілу частину.")
print("Список дозволяє зберігати результати та міняти елементи місцями одним рядком.")
